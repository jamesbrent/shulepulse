import { jsPDF } from 'jspdf'
import { applyPlugin } from 'jspdf-autotable'
applyPlugin(jsPDF)
import { loadLogoBase64, logoSizes, fmtRef } from './pdfLogoHelper'
import { weightedScoreMean, marksCell } from '../../../../services/grading'

const PAGE_W = 210
const PAGE_H = 297
const MARGIN = 18
const CONTENT_W = PAGE_W - MARGIN * 2
const FONT = 'helvetica'
const CENTER = PAGE_W / 2

const BLACK = [0, 0, 0]
const DARK = [51, 51, 51]
const MEDIUM = [102, 102, 102]
const LIGHT = [180, 180, 180]
const FAINT = [230, 230, 230]
const BG = [245, 245, 245]
const WHITE = [255, 255, 255]

function fmt(n) {
  return `KES ${Number(n || 0).toLocaleString('en-KE', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`
}

function fmtDate(d) {
  if (!d) return '—'
  const dt = new Date(d)
  return dt.toLocaleDateString('en-KE', { day: '2-digit', month: 'short', year: 'numeric' })
}

function fmtDateTimeFull(d) {
  if (!d) return '—'
  const dt = new Date(d)
  return dt.toLocaleDateString('en-KE', {
    day: '2-digit', month: 'short', year: 'numeric',
    hour: '2-digit', minute: '2-digit',
  })
}

async function drawSchoolHeader(doc, school, student, title) {
  let y = MARGIN
  const schoolName = school?.name || 'ShulePulse School'
  const schoolAddr = school?.address || ''
  const schoolPhone = school?.phone || ''
  const schoolEmail = school?.email || ''
  const schoolMotto = school?.motto || ''
  const website = school?.website || ''

  const logo = await loadLogoBase64(school)
  if (logo) {
    const ls = logoSizes(logo)
    doc.addImage(logo.dataUrl, 'PNG', CENTER - ls.width / 2, y - 3, ls.width, ls.height)
  } else {
    doc.setDrawColor(...DARK)
    doc.setFillColor(...BG)
    doc.circle(CENTER, y + 7, 10, 'F')
    doc.setDrawColor(...DARK)
    doc.circle(CENTER, y + 7, 10, 'S')
    doc.setFont(FONT, 'bold')
    doc.setFontSize(10)
    doc.setTextColor(...DARK)
    doc.text(schoolName.charAt(0).toUpperCase(), CENTER, y + 10, { align: 'center' })
  }

  y += 24

  doc.setFont(FONT, 'bold')
  doc.setFontSize(16)
  doc.setTextColor(...BLACK)
  doc.text(schoolName.toUpperCase(), CENTER, y, { align: 'center' })

  y += 6
  const contactParts = [schoolAddr, schoolPhone, schoolEmail, website].filter(Boolean)
  if (contactParts.length) {
    doc.setFont(FONT, 'normal')
    doc.setFontSize(8)
    doc.setTextColor(...MEDIUM)
    doc.text(contactParts.join('  |  '), CENTER, y, { align: 'center', maxWidth: CONTENT_W })
    y += 5
  }

  if (schoolMotto) {
    doc.setFont(FONT, 'italic')
    doc.setFontSize(8)
    doc.setTextColor(...LIGHT)
    doc.text(`"${schoolMotto}"`, CENTER, y, { align: 'center' })
    y += 5
  }

  y += 4
  doc.setFont(FONT, 'bold')
  doc.setFontSize(14)
  doc.setTextColor(...DARK)
  doc.text(title, CENTER, y, { align: 'center' })

  y += 6
  doc.setFont(FONT, 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...MEDIUM)
  doc.text(`Student: ${student?.full_name || '—'}  |  Adm: ${student?.admission_number || '—'}  |  Class: ${student?.class || '—'}${student?.stream ? ` ${student.stream}` : ''}`, CENTER, y, { align: 'center' })

  y += 6
  doc.setDrawColor(...DARK)
  doc.setLineWidth(0.5)
  doc.line(MARGIN, y, PAGE_W - MARGIN, y)
  doc.setLineWidth(0.2)
  y += 8

  return y
}

function drawSectionHeader(doc, y, label) {
  doc.setFillColor(...BG)
  doc.rect(MARGIN, y - 4, CONTENT_W, 10, 'F')
  doc.setFont(FONT, 'bold')
  doc.setFontSize(9)
  doc.setTextColor(...BLACK)
  doc.text(label, MARGIN + 4, y + 2)
  return y + 10
}

function drawFooter(doc, y) {
  const remaining = PAGE_H - y - 40
  if (remaining > 0) y += remaining

  doc.setDrawColor(...DARK)
  doc.setLineWidth(0.5)
  doc.line(MARGIN, y, PAGE_W - MARGIN, y)
  doc.setLineWidth(0.2)
  y += 6

  doc.setFont(FONT, 'bold')
  doc.setFontSize(8)
  doc.setTextColor(...DARK)
  doc.text('Generated by ShulePulse ERP', CENTER, y, { align: 'center' })
  y += 4
  doc.setFont(FONT, 'normal')
  doc.setFontSize(7)
  doc.setTextColor(...MEDIUM)
  doc.text(`This is a system-generated report issued on ${fmtDateTimeFull(new Date())}.`, CENTER, y, { align: 'center' })
  y += 3
  doc.text('Valid for official record-keeping purposes.', CENTER, y, { align: 'center' })

  y += 12
  doc.setDrawColor(...LIGHT)
  doc.line(MARGIN, y, MARGIN + 55, y)
  doc.line(PAGE_W - MARGIN - 55, y, PAGE_W - MARGIN, y)
  doc.setFont(FONT, 'normal')
  doc.setFontSize(8)
  doc.setTextColor(...MEDIUM)
  doc.text("Principal's / Administrator's Signature", MARGIN, y + 4)
  doc.text('School Stamp', PAGE_W - MARGIN - 55, y + 4, { align: 'center' })

  y += 14
  doc.setDrawColor(...LIGHT)
  doc.setFillColor(...BG)
  doc.roundedRect(PAGE_W - MARGIN - 20, y - 6, 16, 16, 2, 2, 'FD')
  doc.setFont(FONT, 'normal')
  doc.setFontSize(5)
  doc.setTextColor(...LIGHT)
  doc.text('QR', PAGE_W - MARGIN - 12, y + 2, { align: 'center' })
  doc.text('CODE', PAGE_W - MARGIN - 12, y + 6, { align: 'center' })

  return doc.output('blob')
}

function drawInfoGrid(doc, startY, fields, colCount = 2) {
  const colW = CONTENT_W / colCount
  let y = startY

  fields.forEach((f, i) => {
    const col = MARGIN + (i % colCount) * colW
    const row = Math.floor(i / colCount)
    const yy = y + row * 8
    doc.setFont(FONT, 'normal')
    doc.setFontSize(8)
    doc.setTextColor(...MEDIUM)
    doc.text(f.label, col, yy)
    doc.setFont(FONT, 'bold')
    doc.setFontSize(9)
    doc.setTextColor(...DARK)
    doc.text(f.value, col + 45, yy)
  })

  return y + Math.ceil(fields.length / colCount) * 8 + 6
}

