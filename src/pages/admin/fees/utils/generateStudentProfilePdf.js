export async function generateParentsPdf({ school, student }) {
  const doc = new jsPDF('portrait', 'mm', 'a4')
  let y = await drawSchoolHeader(doc, school, student, 'STUDENT PROFILE — PARENT / GUARDIAN INFORMATION')

  const guardians = student?.guardians || []

  if (guardians.length === 0 && !student?.parent_name) {
    doc.setFont(FONT, 'normal')
    doc.setFontSize(10)
    doc.setTextColor(...LIGHT)
    doc.text('No guardian information recorded.', CENTER, y, { align: 'center' })
    return drawFooter(doc, y + 10)
  }

  guardians.forEach((g, i) => {
    if (y > PAGE_H - 60) {
      doc.addPage()
      y = MARGIN
    }

    y = drawSectionHeader(doc, y, g.relationship ? `${g.relationship.toUpperCase()}` : `GUARDIAN ${i + 1}`)

    const fields = [
      { label: 'Name', value: g.name || '—' },
      { label: 'Relationship', value: g.relationship || '—' },
      { label: 'Phone', value: g.phone || '—' },
      { label: 'Email', value: g.email || '—' },
      { label: 'ID Number', value: g.national_id || '—' },
      { label: 'Occupation', value: g.occupation || '—' },
      { label: 'Address', value: g.address || '—' },
      { label: 'Fee Payer', value: g.is_fee_payer ? 'Yes' : 'No' },
      { label: 'Portal Access', value: g.portal_access ? 'Yes' : 'No' },
      { label: 'SMS Notifications', value: g.sms_notification ? 'Yes' : 'No' },
    ]

    y = drawInfoGrid(doc, y, fields, 2)
  })

  if (student?.parent_name) {
    if (y > PAGE_H - 60) {
      doc.addPage()
      y = MARGIN
    }

    y = drawSectionHeader(doc, y, 'PRIMARY CONTACT (LEGACY)')

    const contactFields = [
      { label: 'Name', value: student.parent_name },
      { label: 'Phone', value: student.parent_phone || '—' },
      { label: 'Email', value: student.parent_email || '—' },
    ]

    y = drawInfoGrid(doc, y, contactFields, 2)
  }

  return drawFooter(doc, y)
}

